; =============================================================================
; psgvoice.asm — メインCPU側プログラム (PSG 音量 DAC 音声再生デモ)
;
; FM-7 の内蔵 PSG (AY-3-8910) だけで音声 WAV を再生するサンプルです。
; PSG にサンプリング再生の機能はありませんが、ミキサ (R7) でトーンと
; ノイズを全て止めると、各チャネルの出力は音量レジスタ (R8-R10) の値
; だけで決まる直流レベルになります。この音量レジスタをサンプルごとに
; 書き換えれば、対数カーブの 16 段 DAC としてそのまま波形を出せます。
;
; ディスク直接ブート (F-BASIC 不要):
;   ブートROM がシリンダ0 サイド0 セクタ1 (256バイト) を $0100 へ読み込んで
;   ジャンプする。残りは IPL 自身が FDC (MB8877 相当、I/O $FD18-$FD1F) を
;   直接操作して読み込む。
;
; カセットテープ (CMT) 起動 (make t77):
;   F-BASIC の LOADM 1 回で本体全体 ($0200-$40FF) をメモリへ展開し、テープ用
;   エントリ TAPENT ($0200) から起動する。FDC は使わず、warm start 前提の
;   前処理 (サブ CPU の CANCEL) を TAPENT が行ってから MAIN へ合流する。
;
; 本プログラムの流れ:
;   IPL  : シリンダ0 サイド0 セクタ2-16 → $0200-$10FF
;            ($0200- = 本体 / $0500-$10FF = サブCPU 用プログラム)
;          シリンダ0 サイド1 セクタ1-16 → $1100-$20FF (PSG データ先頭)
;          シリンダ1 サイド0 セクタ1-16 → $2100-$30FF (PSG データ続き)
;          シリンダ1 サイド1 セクタ1-16 → $3100-$40FF (PSG データ続き)
;   MAIN : デジタルパレット恒等化 (画面はブート直後の 640x200 8色のまま)
;          → サブモニタの正規コマンド ($3F バイトコード) で描画プログラムを
;            サブRAM へ転送・起動 (サブが "HIT SPACE KEY" を表示する)
;          → PSG 初期化 (トーン/ノイズ全ミュート、音量 0)
;          → 以下を繰り返す:
;              SPACE キー待ち
;              → サブへ "FM-7 PSG!" 表示指示
;              → PSG 音量レジスタを毎サンプル書き換えて音声再生 (約 1.6 秒)
;              → サブへ "HIT SPACE KEY" 表示指示 → 先頭へ戻る
;
; PSG の I/O (メイン CPU):
;   $FD0D = コマンドポート (BDIR/BC1 の 2 ビット)
;     $03=アドレスラッチ  $02=データ書込み  $01=データ読出し  $00=不活性
;   $FD0E = データポート (レジスタ番号 / 値)
;   レジスタ書込みは「データポートへ値 → コマンド $03/$02 → $00 (不活性)」
;   の順。コマンドを書いた瞬間のデータポートの値が使われるので、必ず
;   データを先に置くこと。
;
; 再生ループのタイミング:
;   メイン CPU の実効クロックは約 1.79MHz (公称 2MHz からメモリウェイト分を
;   引いた値)。1 サンプルあたり 163 サイクルの固定サイクルループを組み、
;   約 11kHz (データは 11025Hz で作成) を維持する。1 サンプルにつき
;   R8/R9/R10 の 3 本へ同じ音量値を書き (3 チャネル分の振幅が得られる)、
;   アドレスラッチ → データ書込みを 3 回行う。再生中は割込みを一切
;   受けないので、ループのサイクル数がそのままサンプル周期になる。
;
; キー入力:
;   $FD02 bit0=1 でキー入力をメイン側へ回し、$FD03 bit0 (active-low) を
;   ポーリング。$FD01 から読んだコードが $20 (SPACE) のときだけ反応する。
;
; ビルド: lwasm --6809 --format=raw -I assets -o psgvoice_main.bin psgvoice.asm
; =============================================================================

        org     $0100

; ---- 共有RAM 受け渡し領域 (メイン側アドレス、サブ側は $D380- に対応) ----
SH_CMD  equ     $FC82           ; サブモニタコマンドバイト (ブート時のみ)
SH_SEQ  equ     $FC83           ; 更新カウンタ
SH_BC   equ     $FC8B           ; バイトコード領域 (ブート時のみ使用)
SH_PRB  equ     $FC9A           ; HALT 確認用プローブセル
SH_SQV  equ     $FC9B           ; 転送: シーケンス値 (ブート時のみ)
SH_ACK  equ     $FC9C           ; 転送: ack セル (ブート時のみ)
SH_REQ  equ     $FC9D           ; リクエスト (1=HIT SPACE KEY / 2=FM-7 PSG!)
SH_RACK equ     $FC9E           ; リクエスト ack
SH_RDY  equ     $FC9F           ; サブの初期描画完了マーカー ($A5)
SH_PAY  equ     $FCA0           ; ペイロード (ブート時 96 バイト)

SUBIMG  equ     $0500           ; サブプログラムのロード先 (メイン側の一時置場)
NCHUNK  equ     32              ; 転送チャンク数 (32 x 96 = 3072 バイト)
PSGDAT  equ     $1100           ; PSG データの先頭 (IPL がロード済)

; PSGRATE / PSGNSMP / PSGDATSZ は psgdef.s (wav2psg.py が生成) が定義する
        include "psgdef.s"

PSGEND  equ     PSGDAT+PSGDATSZ ; PSG データの終端 (この直前まで再生)

; =============================================================================
; IPL: 読み込み表 (LDTBL) に従い、残りのセクタを全て読み込む
;
; FDC レジスタ (DP=$FD):
;   $FD18 ステータス(R)/コマンド(W)  $FD19 トラック  $FD1A セクタ
;   $FD1B データ  $FD1C サイド(bit0)  $FD1D ドライブ(bit1-0)+モータ(bit7)
;   $FD1F bit7=DRQ / bit6=IRQ(コマンド完了)
; =============================================================================
IPL:    orcc    #$50
        lds     #$0100          ; スタックはゼロページへ
        lda     #$FD
        tfr     a,dp            ; I/O は DP=$FD の直接アドレシングで参照

        ; ---- ドライブ0 選択 + モータON、サイド0 ----
        lda     #$80
        sta     <$1D            ; モータON, ドライブ0
        clr     <$1C            ; サイド0

        ; ---- RESTORE: ヘッドとトラックレジスタをトラック0 へ ----
        lda     <$18            ; 直前のステータス/IRQ を読み捨て
        lda     #$03            ; RESTORE (ステップレート最遅)
        sta     <$18
IPLRW:  lda     <$1F
        bita    #$40            ; IRQ = コマンド完了
        beq     IPLRW
        lda     <$18            ; 完了ステータス読み出し (IRQ クリア)

        ; ---- 表に従って各トラックを読む ----
        ldy     #LDTBL
IPLPH:  lda     ,y              ; シリンダ ($FF = 終端)
        cmpa    #$FF
        beq     IPLGO
        cmpa    CURCYL
        beq     IPLSD           ; 同じシリンダ: シーク不要
        sta     CURCYL
        bsr     SEEKT
IPLSD:  lda     1,y
        sta     <$1C            ; サイド
        ldx     3,y             ; 読み込み先
        lda     2,y             ; 先頭セクタ番号
IPLLP:  bsr     RDSEC
        bcs     IPLLP           ; エラー時は同一セクタをリトライ
        leax    256,x
        inca
        cmpa    #17
        bne     IPLLP           ; セクタ16 まで読む
        leay    5,y
        bra     IPLPH
IPLGO:  jmp     MAIN

CURCYL: fcb     0               ; 現在のシリンダ (RESTORE 直後は 0)

; 読み込み表: [シリンダ, サイド, 先頭セクタ, 読み込み先(2バイト)] x N + $FF
LDTBL:  fcb     0,0,2
        fdb     $0200           ; 本体の続き + サブCPU 用プログラム ($0500-)
        fcb     0,1,1
        fdb     $1100           ; PSG データ先頭
        fcb     1,0,1
        fdb     $2100           ; PSG データ続き
        fcb     1,1,1
        fdb     $3100           ; PSG データ続き
        fcb     $FF

; -----------------------------------------------------------------------------
; SEEKT: トラック A へシーク (データレジスタに目標トラックを置いて SEEK)
; -----------------------------------------------------------------------------
SEEKT:  sta     <$1B            ; データレジスタ = 目標トラック
        lda     #$1B            ; SEEK (ヘッドロード / ベリファイ無し / 最遅)
        sta     <$18
SEEKW:  lda     <$1F
        bita    #$40
        beq     SEEKW
        lda     <$18            ; 完了ステータス読み出し (IRQ クリア)
        rts

; -----------------------------------------------------------------------------
; RDSEC: セクタ A (256バイト) をアドレス X へ読む。A/X は保存。エラー時 C=1
; -----------------------------------------------------------------------------
RDSEC:  pshs    a,x
        sta     <$1A            ; セクタレジスタ
        lda     #$80            ; READ SECTOR (単レコード)
        sta     <$18
RDLP:   lda     <$1F
        bmi     RDGET           ; bit7=DRQ: データ引き取り
        bita    #$40
        beq     RDLP            ; DRQ も IRQ も無し: 待ち継続
        lda     <$18            ; IRQ: 完了ステータス取得 (IRQ クリア)
        anda    #$1C            ; RNF($10)/CRC($08)/LOST DATA($04)
        beq     RDOK
        puls    a,x
        orcc    #$01            ; C=1: エラー
        rts
RDGET:  lda     <$1B
        sta     ,x+
        bra     RDLP
RDOK:   puls    a,x
        andcc   #$FE            ; C=0: 正常
        rts

        zmb     $0200-*

; =============================================================================
; TAPENT: カセットテープ (CMT) 起動時のエントリ ($0200)
;
;   make t77 が生成するテープ (T77/WAV) は、LOADM 1 回でロードバッファへ
;   本体全体を読み込み、トランポリンが $0200- へ展開してからここへ JMP
;   してくる (割込はマスク済み、ROM オーバレイは OFF、スタックは張り直し済み)。
;
;   テープ起動は F-BASIC 稼働中 (warm start) からの突入なので、サブ CPU は
;   BASIC のサブシステム処理の途中に居て、ディスク起動が前提とする
;   「サブモニタのコマンド待ちループ」に居ない。そのまま MAIN の転送手順を
;   流しても同期しないため、まず CANCEL ($FD05 bit6) でサブの実行中処理を
;   中断させ、コマンド待ちループへ戻してから MAIN へ落ちる。
;
;   CANCEL は割込としてサブの命令境界で受理されるため、1 回目で要求を
;   確定させ、少し空転してから再発行して確実に割込を通し、サブが割込処理を
;   終えてコマンド待ちへ復帰するのを空転で待つ。
;   (ディスク起動では IPL が MAIN へ直接ジャンプするので、ここは通らない)
; =============================================================================
TAPENT: orcc    #$50            ; 割込禁止 (warm start では BASIC の割込が生きている)
        lds     #$0100          ; スタックはゼロページへ (MAIN と同じ)
        lda     #$FD
        tfr     a,dp
        lda     #$40
        sta     <$05            ; CANCEL 要求 (bit6=1 / bit7=0=RUN のまま)
        ldb     #32
TCDL1:  decb                    ; サブの命令境界で要求が確定するのを待つ
        bne     TCDL1
        lda     #$40
        sta     <$05            ; 再発行で割込を確実に立てる
        ldx     #2000
TCDL2:  leax    -1,x            ; サブが割込処理を終えコマンド待ちへ戻るのを待つ
        bne     TCDL2
        ; そのまま MAIN へ (fall through)

; =============================================================================
; MAIN: 画面初期化・サブ起動・SPACE キー待ちと PSG 再生のループ
; =============================================================================
MAIN:   orcc    #$50
        lds     #$0100
        lda     #$FD
        tfr     a,dp

        ; ---- デジタルパレット恒等化 ($FD38-$FD3F ← 0-7) ----
        ;      画面モードはブート直後の 640x200 8色のまま変更しない
        ldx     #$FD38
        clrb
DPLP:   stb     ,x+
        incb
        cmpb    #8
        bne     DPLP
        clr     <$37            ; $FD37: マルチページマスク解除

        ; =====================================================================
        ; サブCPUプログラムの転送と起動 — サブモニタの正規コマンド $3F を使う
        ;
        ; サブモニタは共有RAM (メイン $FC80-$FCFF = サブ $D380-$D3FF) の
        ; コマンドバイト (サブ $D382) を監視し、非ゼロなら実行して 0 に戻す。
        ; コマンド $3F はサブ $D38B からのバイトコード列を解釈する:
        ;   $90            : 終了
        ;   $91 src dst len: メモリ転送 (各2バイト、ビッグエンディアン)
        ;   $93 addr       : サブ空間の機械語を JSR で呼び出す
        ; これを使い、サブプログラムを 96 バイト x NCHUNK チャンクで
        ; サブRAM $C100- へ転送し、最後に $93 で起動する。
        ;
        ; 注意: 共有RAM はデュアルポート調停のためサブCPUが HALT している間
        ; しかメイン側から読み書きできない。全アクセスを HALT/RUN で包む。
        ; =====================================================================

WBUSY:  lda     <$04
        bmi     WBUSY           ; $FD04 bit7=1 の間はビジー

        lda     #1
        sta     CHKN            ; チャンク番号 (= ack 照合値)
        ldx     #SUBIMG         ; 転送元 (メイン側、IPL がロード済)
        ldy     #$C100          ; 転送先 (サブ側)

CHUNK:  lbsr    HALTON
        lda     SH_CMD
        beq     CHGO            ; モニタがアイドルなら送信
        lbsr    HALTOFF         ; まだ前コマンド処理中: 実行時間を与える
        lbsr    DLYS
        lbra    CHUNK
CHGO:   ; ---- (HALT中) ペイロード 96 バイト → $FCA0 (サブ $D3A0) ----
        ldu     #SH_PAY
CPY96:  lda     ,x+
        sta     ,u+
        cmpu    #$FD00
        bne     CPY96
        ; ---- バイトコード組立: [$91 $D3A0 dst 96] [$91 $D39B $D39C 1] [$90] ----
        ldu     #SH_BC
        lda     #$91
        sta     ,u+
        ldd     #$D3A0
        std     ,u++            ; src = ペイロード (サブ側番地)
        sty     ,u++            ; dst
        ldd     #96
        std     ,u++            ; len
        lda     #$91
        sta     ,u+
        ldd     #$D39B
        std     ,u++            ; src = シーケンス値セル
        ldd     #$D39C
        std     ,u++            ; dst = ack セル
        ldd     #1
        std     ,u++            ; len = 1
        lda     #$90
        sta     ,u              ; 終了
        lda     CHKN
        sta     SH_SQV          ; シーケンス値
        clr     SH_ACK          ; ack クリア
        lda     #$3F
        sta     SH_CMD          ; コマンド発行
        lbsr    HALTOFF         ; サブ再開 → モニタがコマンドを実行
WACK:   lbsr    DLYS            ; サブに実行時間を与える
        lbsr    HALTON
        lda     SH_ACK
        cmpa    CHKN
        bne     WNOT            ; ack 未達
        lda     SH_CMD
        bne     WNOT            ; コマンド未消費
        lbsr    HALTOFF         ; チャンク完了
        leay    96,y
        inc     CHKN
        lda     CHKN
        cmpa    #NCHUNK+1
        bne     CHUNK
        lbra    TKDONE
WNOT:   lbsr    HALTOFF
        lbra    WACK

        ; ---- 共有RAM 初期化 + 起動コマンド (HALT中に書く) ----
TKDONE: lbsr    HALTON
        clr     SH_REQ
        clr     SH_RACK
        clr     SH_RDY
        clr     SH_SEQ
        ; 起動: バイトコード $93 (CALL $C100)。デモは戻らない
        ldu     #SH_BC
        lda     #$93
        sta     ,u+
        ldd     #$C100
        std     ,u
        lda     #$3F
        sta     SH_CMD
        lbsr    HALTOFF         ; サブ再開 → デモ開始

        ; ---- サブの初期描画完了 ("HIT SPACE KEY" 表示) を待つ ----
WRDY:   lbsr    DLYS
        lbsr    HALTON
        lda     SH_RDY
        cmpa    #$A5
        beq     RDYOK
        lbsr    HALTOFF
        bra     WRDY
RDYOK:  lbsr    HALTOFF

        ; ---- デモループ ----
        clr     <$1D            ; FDD モータ停止 (以後ディスクは使わない)
        lda     #$01
        sta     <$02            ; $FD02 bit0=1: キー入力をメイン側へ
                                ;   CC の割込みマスクは orcc #$50 のままなので
                                ;   ベクタへは飛ばず、$FD03 のポーリングで受ける
        lbsr    PSGINI          ; PSG 初期化 (全ミュート)
DEMOLP: lbsr    KEYDRN          ; 再生中に押されていたキーを読み捨てる
        lbsr    SPCWT           ; SPACE キーが押されるまで待つ
        lda     #2
        lbsr    SUBREQ          ; "FM-7 PSG!" へ書き換え
        lbsr    PSGPLY          ; PSG 音量 DAC で音声再生 (再生中はキーを見ない)
        lda     #1
        lbsr    SUBREQ          ; "HIT SPACE KEY" へ戻す
        bra     DEMOLP

; -----------------------------------------------------------------------------
; HALTON/HALTOFF: サブCPUの停止・再開 (A を破壊)
;   HALTON は $FD05 の bit7 を待つだけでなく、共有RAM へ実際に書けることを
;   プローブセルの書込み/読出しで確かめる。
; DLYS: 短い待ち (サブへ実行時間を与える)
; -----------------------------------------------------------------------------
HALTON: lda     #$80
        sta     <$05            ; $FD05 bit7=1: HALT 要求
HLT1:   lda     <$05
        bpl     HLT1            ; HALT 完了 (bit7=1) を待つ
        lda     #$A5
        sta     SH_PRB          ; 共有RAM を掴めたか確認 (書けなければ落ちる)
        lda     SH_PRB
        cmpa    #$A5
        bne     HLT1            ; まだ掴めていない: 待ち直す
        rts
HALTOFF:
        clr     <$05            ; RUN
        rts
DLYS:   pshs    x
        ldx     #300
DLY1:   leax    -1,x
        bne     DLY1
        puls    x,pc

; -----------------------------------------------------------------------------
; SUBREQ: サブへリクエスト A を渡し、ack が返るまで待つ
;   共有RAM アクセスは HALT で包む。更新カウンタ (SH_SEQ) を +1 して知らせ、
;   サブが同じ値を SH_RACK へ書き返したら完了とする。
; -----------------------------------------------------------------------------
SUBREQ: sta     REQV
        bsr     HALTON
        lda     REQV
        sta     SH_REQ
        inc     SEQC
        lda     SEQC
        sta     SH_SEQ
        bsr     HALTOFF
SRW:    bsr     DLYS
        bsr     HALTON
        lda     SH_RACK
        cmpa    SEQC
        beq     SRDONE
        bsr     HALTOFF
        bra     SRW
SRDONE: bsr     HALTOFF
        rts

; -----------------------------------------------------------------------------
; KEYDRN: 溜まっているキーコードを読み捨てる (再生中の打鍵を持ち越さない)
; -----------------------------------------------------------------------------
KEYDRN: lda     <$03            ; $FD03: IRQ ステータス (bit0=0 でキーあり)
        bita    #$01
        bne     KDEND           ; 溜まっていない
        lda     <$01            ; 読み捨て (読むとフラグ解除)
        bra     KEYDRN
KDEND:  rts

; -----------------------------------------------------------------------------
; SPCWT: SPACE キー ($20) が押されるまで待つ ($FD03 bit0 のポーリング)
; -----------------------------------------------------------------------------
SPCWT:  lda     <$03
        bita    #$01
        bne     SPCWT           ; キーなし
        lda     <$01            ; キーコード取得
        cmpa    #$20            ; SPACE 以外は無視
        bne     SPCWT
        rts

; =============================================================================
; PSG (AY-3-8910) アクセス
;
;   $FD0D = コマンドポート  $03=アドレスラッチ / $02=データ書込み / $00=不活性
;   $FD0E = データポート
;
;   コマンドを書いた瞬間のデータポートの値が使われるため、必ずデータを
;   先に置いてからコマンドを書く。各操作の後は $00 (不活性) へ戻す。
; =============================================================================

; -----------------------------------------------------------------------------
; PSGW: PSG レジスタ A に値 B を書く (DP=$FD 前提)。A 破壊、B/X/Y 保存
; -----------------------------------------------------------------------------
PSGW:   sta     <$0E            ; データ = レジスタ番号
        lda     #$03
        sta     <$0D            ; アドレスラッチ
        clr     <$0D            ; 不活性
        stb     <$0E            ; データ = 値
        lda     #$02
        sta     <$0D            ; データ書込み
        clr     <$0D            ; 不活性
        rts

; -----------------------------------------------------------------------------
; PSGINI: トーン/ノイズを全て止め、音量を 0 にする
;   R7 (ミキサ) = $3F: トーン A-C とノイズ A-C を全て禁止。
;   これで出力は音量レジスタの値だけで決まる直流レベルになる。
; -----------------------------------------------------------------------------
PSGINI: lda     #$07
        ldb     #$3F
        bsr     PSGW            ; ミキサ: 全ミュート
PSGOFF: lda     #$08
        clrb
        bsr     PSGW            ; 音量 A = 0
        lda     #$09
        clrb
        bsr     PSGW            ; 音量 B = 0
        lda     #$0A
        clrb
        bsr     PSGW            ; 音量 C = 0
        rts

; =============================================================================
; PSGPLY: PSG 音量 DAC による音声再生
;
;   データは 1 バイトに 2 サンプル (上位ニブルが先)。1 サンプルごとに
;   R8/R9/R10 の 3 本へ同じ音量値 (0-15) を書く。
;
;   タイミングは固定サイクルループで作る (割込みは禁止のまま):
;     1 サンプル = 163 サイクル (奇数サンプル 162 / 偶数サンプル 164 の平均)
;     実効クロック約 1.79MHz ÷ 163 ≒ 11.0kHz ≒ データレート 11025Hz
;   WRVOL 1 回 = 34 サイクル、3 レジスタで 102 サイクル。残りは nop 等で
;   調整する。アドレスラッチは書込み後も保持されるが、R8→R9→R10 と
;   切り替えるため毎回ラッチし直す。
; =============================================================================

; WRVOL: 音量レジスタ \1 へ B (0-15) を書く (34 サイクル)
WRVOL   macro
        lda     #\1             ; 2
        sta     <$0E            ; 4  データ = レジスタ番号
        lda     #$03            ; 2
        sta     <$0D            ; 4  アドレスラッチ
        clr     <$0D            ; 6  不活性
        stb     <$0E            ; 4  データ = 音量値
        lda     #$02            ; 2
        sta     <$0D            ; 4  データ書込み
        clr     <$0D            ; 6  不活性
        endm

; PAD8: 8 サイクル消費 (レジスタ・フラグへの影響なし)
PAD8    macro
        exg     a,a             ; 8
        endm

PSGPLY: ldx     #PSGDAT
PLYLP:  ; ---- サンプル1 (上位ニブル): 4+8+102+48 = 162 サイクル ----
        ldb     ,x              ; 4
        lsrb                    ; 2
        lsrb                    ; 2
        lsrb                    ; 2
        lsrb                    ; 2  B = 上位ニブル
        WRVOL   8               ; 34
        WRVOL   9               ; 34
        WRVOL   10              ; 34
        PAD8                    ; 8
        PAD8                    ; 8
        PAD8                    ; 8
        PAD8                    ; 8
        PAD8                    ; 8
        PAD8                    ; 8
        ; ---- サンプル2 (下位ニブル): 8+102+44+10 = 164 サイクル ----
        ldb     ,x+             ; 6
        andb    #$0F            ; 2  B = 下位ニブル
        WRVOL   8               ; 34
        WRVOL   9               ; 34
        WRVOL   10              ; 34
        PAD8                    ; 8
        PAD8                    ; 8
        PAD8                    ; 8
        PAD8                    ; 8
        PAD8                    ; 8
        nop                     ; 2
        nop                     ; 2
        cmpx    #PSGEND         ; 4
        lbne    PLYLP           ; 6 (分岐成立時。ループが長く bne は届かない)
        ; ---- 終了: 音量を 0 へ戻す ----
        lbsr    PSGOFF
        rts

; ---- ワークエリア ----
CHKN:   fcb     0               ; 転送チャンク番号
SEQC:   fcb     0               ; リクエストの更新カウンタ
REQV:   fcb     0               ; リクエストコードの一時退避

        end
