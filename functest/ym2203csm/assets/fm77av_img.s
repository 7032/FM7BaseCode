* 元画像 FM77AV.PNG (320x200、実色数 62)
* 非圧縮 48000 バイト -> 圧縮後 36707 バイト (76.5%)
*
* ---------------------------------------------------------------------
* 方式
* ---------------------------------------------------------------------
*   元画像はパレット画像で実色数が 64 以下なので、色を量子化せず
*   アナログパレットの 64 エントリへ元画像の色をそのまま設定し、
*   画面には 6 ビットのパレット添字だけを置く。誤差は 1 チャネル
*   8 ビット -> 4 ビットの丸めだけ。ディザリングは行っていない。
*
* ---------------------------------------------------------------------
* VRAM 構成 (320x200 4096色モード、サブCPU から見た配置)
* ---------------------------------------------------------------------
*   1 ライン 40 バイト (MSB が左端のドット)、1 プレーン 8000 バイト。
*   ページ0 ($D430 bit5=0): $0000 B3 / $2000 B2 / $4000 R3 / $6000 R2 /
*                           $8000 G3 / $A000 G2
*   ページ1 ($D430 bit5=1): $0000 B1 / $2000 B0 / $4000 R1 / $6000 R0 /
*                           $8000 G1 / $A000 G0
*   12 枚から 1 ドット 12 ビットのアナログパレット添字が作られる:
*     添字 = (G<<8) | (R<<4) | B  (各 4 ビット、B3/R3/G3 が各ニブルの MSB)
*
* ---------------------------------------------------------------------
* プレーンとパレット添字ビットの対応 (本データの割当)
* ---------------------------------------------------------------------
*   ページ1 は使わない (全ビット 0)。よってページ0 の 6 面が担う
*   12 ビット添字の bit11/10/7/6/3/2 だけが有効で、他は常に 0。
*   ピクセルのパレット添字 n (0..63) のビット割当:
*
*     n bit5 -> G3 プレーン (ページ0 $8000) -> 12 ビット添字 bit11
*     n bit4 -> G2 プレーン (ページ0 $A000) -> 12 ビット添字 bit10
*     n bit3 -> R3 プレーン (ページ0 $4000) -> 12 ビット添字 bit7
*     n bit2 -> R2 プレーン (ページ0 $6000) -> 12 ビット添字 bit6
*     n bit1 -> B3 プレーン (ページ0 $0000) -> 12 ビット添字 bit3
*     n bit0 -> B2 プレーン (ページ0 $2000) -> 12 ビット添字 bit2
*
*   すなわち n = (nG<<4)|(nR<<2)|nB (各 2 ビット) に対し
*            12 ビット添字 = (nG<<10)|(nR<<6)|(nB<<2)
*   imgpal はこの 12 ビット添字の番地へ色を書く。
*
* ---------------------------------------------------------------------
* パレットテーブル imgpal (1 エントリ 5 バイト、IMGPALN 個)
* ---------------------------------------------------------------------
*   先頭から順に、そのまま下記の I/O へ書けばよい (メインCPU 側):
*     +0 -> $FD30   パレット添字の上位 4 ビット (12 ビット添字の bit11-8)
*     +1 -> $FD31   パレット添字の下位 8 ビット (12 ビット添字の bit7-0)
*     +2 -> $FD32   青 B (下位ニブルのみ有効)
*     +3 -> $FD33   赤 R (下位ニブルのみ有効)
*     +4 -> $FD34   緑 G (下位ニブルのみ有効)
*   これを IMGPALN 回繰り返す。FM77AV 以降でのみ書き込むこと
*   (FM-7 には $FD30-$FD34 は無い)。
*
* ---------------------------------------------------------------------
* 展開後データの並び (非圧縮ストリーム)
* ---------------------------------------------------------------------
*   B3, B2, R3, R2, G3, G2 の順に 8000 バイトずつ連結 (ページ0 のみ)。
*   合計 48000 バイト。展開側は 8000 バイトごとに書き込み先を
*   $0000 / $2000 / $4000 / $6000 / $8000 / $A000 と進める。
*   ページ1 は全 0 のままにすること (クリアしておく)。
*
* ---------------------------------------------------------------------
* RLE 圧縮形式 (imgdata はこの形式の 1 本のストリーム)
* ---------------------------------------------------------------------
*   制御バイト C を読む
*     C = $00        : 終端 (展開終了)
*     C bit7 = 1     : ラン。n = C & $7F (1..127)。続く 1 バイト V を
*                      n 回出力する。トークン長 2 バイト
*     C bit7 = 0     : リテラル。n = C (1..127)。続く n バイトを
*                      そのまま出力する。トークン長 1+n バイト
*   n は必ず 1..127 ($00 は終端専用、$80 は出現しない)。
*   トークンはプレーン境界 (8000 バイト) をまたぐことがある。展開側は
*   出力バイト数を数え、8000 バイトごとに書き込み先を切り替えること。
*   展開後の総バイト数は IMGPLANES * IMGPLNSZ に一致する。
*
* 展開ルーチンの骨子 (X=圧縮データ、Y=出力先):
*   loop   lda ,x+ / beq done / bmi runtok
*          tfr a,b
*   litlp  lda ,x+ / sta ,y+ / decb / bne litlp / bra loop
*   runtok anda #$7F / tfr a,b / lda ,x+
*   runlp  sta ,y+ / decb / bne runlp / bra loop
*   done

* ---------------------------------------------------------------------
* 重ね書き文字用の色 IMGTXTCOL
* ---------------------------------------------------------------------
*   画像が使っていない空きスロットへ文字色 (RGB4 = FF0) を置いた。
*   このスロットの添字 IMGTXTCOL = 31 で文字を描けば、画像の発色を
*   一切変えずに文字を重ねられる。空きスロットの色を変えるだけなので
*   文字色を変えても imgdata (画像本体) は 1 バイトも変わらない。
*   文字を重ねる側は、ページ0 の 6 面それぞれについて
*     そのプレーンが担う IMGTXTCOL のビットが 1 なら 字形ビットを OR、
*     0 なら 字形ビットの反転を AND
*   すればよい (地の画像を壊さない read-modify-write)。
*
IMGPALN    equ 64
IMGPLANES  equ 6
IMGPLNSZ   equ 8000
IMGDATSZ   equ 36707
IMGTXTCOL  equ 31

